/** Fill {placeholders} in a translated string.
 *
 *  Every screen that needed this was defining its own copy inline; the new ones import
 *  this instead. Kept beside the strings it fills, because the placeholder names are part
 *  of the translation - a Georgian string that spells `{n}` differently is a silent gap. */
export function text(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (out, [k, v]) => out.replace(`{${k}}`, String(v)),
    template,
  )
}
